"""result_report/generated_numbers_qml.tex and results/NUMBERS_qml.md from the Phase 4 result files (main .venv).

Macro style of Optimization/report/make_numbers.py: \\providecommand + \\renewcommand, values never typed by hand.
Values over seeds are means (sd in NUMBERS_qml.md). Regrets are against the repaired labels (primary certification).
"""
import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from qml import common as C  # noqa: E402
from qml.report import certifications, collect, latest  # noqa: E402

NAMES = {"PQC-full": "PQCFull", "PQC-product": "PQCProduct", "NN-tuned": "NNTuned", "NN-matched": "NNMatched",
         "RFF-ridge": "RFFRidge", "lookup-2D": "LookupTwoD", "lookup-nX": "LookupNX"}
SPLITS = {"test_bulk": "TestBulk", "test_tail": "TestTail", "ref_bulk": "RefBulk", "ref_tail": "RefTail"}
FIELDS = {"median": ("Median", True), "pct_le_1e-06": ("PctSix", False), "pct_no_key": ("PctNoKey", False)}


def tex(v, sci):
    if v is None or not np.isfinite(v):
        return "--"
    if sci:
        m, e = f"{v:.2e}".split("e")
        return f"\\ensuremath{{{m}\\times 10^{{{int(e)}}}}}"
    return f"{v:.1f}"


def main():
    mf, _ = certifications()   # primary: certification against the repaired labels (Amendment 4)
    M = json.load(open(mf))
    lat_f = latest("qml_latency_*/latency.json")
    lat = json.load(open(lat_f))
    rows = []
    for model, mn in NAMES.items():
        for split, sn in SPLITS.items():
            for k in ("k0", "k1", "k3"):
                for field, (fn, sci) in FIELDS.items():
                    vals = [x for x in collect(M, "dense", model, split, k, field) if x is not None]
                    if not vals:
                        continue
                    kn = {"k0": "", "k1": "HybOne", "k3": "HybThree"}[k]
                    rows.append((f"QML{mn}{sn}{kn}{fn}", float(np.mean(vals)),
                                 float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0, sci,
                                 f"dense, {split}, {k}, {field}, mean over {len(vals)} seed(s)", mf))
        if model in lat["models"]:
            rows.append((f"QML{mn}LatencyUs", lat["models"][model]["batch1_end_to_end_us"], 0.0, False,
                         "batch-1 end-to-end median, µs", lat_f))
    T = M["timing"]
    rows += [("QMLColdSolveUs", T["batch1_cold"]["end_to_end_us_median"], 0.0, False, "batch-1 cold solve, µs", mf),
             ("QMLWarmSolveUs", T["batch1_warm"]["end_to_end_us_median"], 0.0, False, "batch-1 warm solve, µs", mf)]
    rows += [(f"QMLNewton{w}Us", T["batch1_kstep"][i]["end_to_end_us_median"], 0.0, False,
              f"batch-1 k={i + 1} Newton steps, µs", mf) for i, w in enumerate(("One", "Two", "Three"))]
    for name in ("cold", "warm"):
        for split, sn in (("test_bulk", "TestBulk"), ("test_tail", "TestTail")):
            b = M["baselines"][name][split]
            rows.append((f"QML{name.capitalize()}{sn}PctSix", b["pct_le_1e-06"], 0.0, False,
                         f"{name} baseline, {split}, % within 1e-6", mf))
    out_tex = os.path.join(ROOT, "result_report", "generated_numbers_qml.tex")
    with open(out_tex, "w") as fh:
        fh.write("% AUTO-GENERATED by qml/make_numbers_qml.py -- DO NOT EDIT.\n")
        for name, v, _, sci, _, _ in rows:
            fh.write(f"\\providecommand{{\\{name}}}{{}}\\renewcommand{{\\{name}}}{{{tex(v, sci)}}}\n")
    md = ["# Generated numbers, QML study (do not edit; `python qml/make_numbers_qml.py`)", "",
          "| macro | value | sd over seeds | meaning | source |", "|---|---|---|---|---|"]
    md += [f"| `\\{n}` | {v:.6g} | {s:.3g} | {m} | `{os.path.relpath(src, ROOT)}` |" for n, v, s, _, m, src in rows]
    with open(os.path.join(C.RESULTS, "NUMBERS_qml.md"), "w") as fh:
        fh.write("\n".join(md) + "\n")
    print(f"wrote {len(rows)} values to {os.path.relpath(out_tex, ROOT)} and results/NUMBERS_qml.md", flush=True)


if __name__ == "__main__":
    main()
